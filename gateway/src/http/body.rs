//! Response ownership, bounded body collection and wire-format errors.
use crate::runtime::request::RequestHandle;
use anyhow::Result;
use bytes::Bytes;
use futures::stream::BoxStream;
use http_body_util::{BodyExt, Full, combinators::BoxBody};
use hyper::{
    Response, StatusCode,
    body::{Frame, Incoming},
};
use std::{convert::Infallible, sync::Mutex, time::Duration};

pub(super) type Body = BoxBody<Bytes, anyhow::Error>;
pub(super) struct ResponseGuard {
    pub(super) trace: Option<crate::telemetry::Trace>,
    pub(super) handle: RequestHandle,
    pub(super) finished: bool,
}
impl ResponseGuard {
    pub(super) fn finish(&mut self) {
        self.finished = true;
        self.handle.finish_response();
    }
}
impl Drop for ResponseGuard {
    fn drop(&mut self) {
        if let Some(trace) = &self.trace {
            trace.cancelled();
        }
        if !self.finished {
            self.handle.cancel();
        }
    }
}
pub(super) struct SyncStream(pub(super) Mutex<BoxStream<'static, Result<Frame<Bytes>>>>);
impl futures::Stream for SyncStream {
    type Item = Result<Frame<Bytes>>;
    fn poll_next(
        self: std::pin::Pin<&mut Self>,
        cx: &mut std::task::Context<'_>,
    ) -> std::task::Poll<Option<Self::Item>> {
        self.0.lock().unwrap().as_mut().poll_next(cx)
    }
}
// Record failures generated by the host after trace admission, before guard cancellation.
pub(super) async fn trace_failure(trace: &crate::telemetry::Trace, status: u16, message: &str) {
    let _ = trace
        .metadata(serde_json::json!({"event": "headers", "status": status}))
        .await;
    let _ = trace.finish(false, Some(message.into())).await;
}
pub(super) async fn collect(
    mut body: Incoming,
    limit: usize,
    idle_timeout: Duration,
) -> std::result::Result<Bytes, Box<Response<Body>>> {
    let mut bytes = bytes::BytesMut::new();
    while let Some(frame) = tokio::time::timeout(idle_timeout, body.frame())
        .await
        .map_err(|_| {
            Box::new(error(
                408,
                "request_timeout",
                "request body timed out",
                None,
            ))
        })?
    {
        let frame =
            frame.map_err(|_| Box::new(error(400, "request_body", "request body failed", None)))?;
        if let Ok(data) = frame.into_data() {
            if bytes.len().saturating_add(data.len()) > limit {
                return Err(Box::new(error(
                    413,
                    "body_limit",
                    "request body exceeds limit",
                    None,
                )));
            }
            bytes.extend_from_slice(&data);
        }
    }
    Ok(bytes.freeze())
}
pub(super) fn full(bytes: Bytes) -> Body {
    Full::new(bytes)
        .map_err(|never: Infallible| match never {})
        .boxed()
}
pub(super) fn identity_error(error_value: anyhow::Error) -> Response<Body> {
    if let Some(e) = error_value.downcast_ref::<crate::identity::Error>() {
        {
            use crate::identity::ErrorKind;
            let status = match e.kind {
                ErrorKind::InvalidInput => 400,
                ErrorKind::Unauthenticated => 401,
                ErrorKind::Forbidden => 403,
                ErrorKind::NotFound => 404,
                ErrorKind::Conflict => 409,
                ErrorKind::Busy => 429,
            };
            error(status, "identity_error", e.message, None)
        }
    } else {
        eprintln!("identity operation failed: {error_value:#}");
        error(
            503,
            "identity_unavailable",
            "identity service unavailable",
            None,
        )
    }
}
pub(super) fn json(status: u16, value: impl serde::Serialize) -> Response<Body> {
    Response::builder()
        .status(status)
        .header("content-type", "application/json")
        .body(full(Bytes::from(
            serde_json::to_vec(&value).expect("HTTP response must serialize"),
        )))
        .unwrap()
}
pub(super) fn error(
    status: u16,
    code: &str,
    message: &str,
    plugin: Option<&str>,
) -> Response<Body> {
    json(
        StatusCode::from_u16(status).unwrap().as_u16(),
        serde_json::json!({"code":code,"message":message,"plugin":plugin}),
    )
}
